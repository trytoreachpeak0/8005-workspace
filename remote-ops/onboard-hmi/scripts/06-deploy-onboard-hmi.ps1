#Requires -Version 7
<#
.SYNOPSIS
    Deploys the OnboardHmi half of a WIRE_TO_GATE release package to one AGV
    onboard machine. Runs on the control host.

.DESCRIPTION
    The same joint package that 15-deploy-control-server.ps1 installs on the
    factory server carries the onboard half. This script delivers it:

        GitHub artifact -> control host -> scp -> agv01 -> staged, configured

    It stops before starting anything. Three reasons, and none of them is
    caution for its own sake:

      * the target is a production vehicle that moves. Starting the client is
        an action with a physical consequence, and RELEASE-CANDIDATE.md
        section 11 requires a per-occasion authorisation and an on-site safety
        GO for exactly that class of action;
      * SQCD.Agv.Wpf is an interactive WPF application, not a service. There is
        no stop-swap-start; it needs a desktop session, and sshd gives us
        session 0, where a window is owned by a desktop nobody is looking at;
      * the readiness gate belongs to a person. Section 8 says a clean session
        only reaches Ready when the vehicle-safety projection returns
        motionState=STOPPED with fresh evidence. Watching that is the point of
        having someone there.

    Deployment still never starts anything. Since 2026-09-04 starting is its own
    step rather than a walk to the vehicle: 10-start-onboard-stack.ps1 brings up
    the simulator and the client, in that order, in the interactive session. It
    narrows the first two reasons above -- the authorisation is now expressed by
    somebody deliberately invoking that script, and nothing invokes it as a side
    effect of this one -- and changes nothing about the third.

    What this script does do is everything up to that line: verify the package,
    fill in the site values, reject a configuration the client would refuse at
    startup, place the binaries, set the credentials, and prove from the vehicle
    itself that the server it was pointed at answers.

.PARAMETER RunId
    GitHub Actions run to deploy. Omit to take the most recent successful
    `release` run in the ControlServer repository -- the joint package is built
    there.

.PARAMETER PackagePath
    Deploy a zip already on disk instead of downloading one.

.PARAMETER SshAlias
    Which vehicle. One alias per car; the site file is named after it.

.PARAMETER OnboardPort
    The ControlServer's NDJSON port, written into wireToGate.port. The default
    58005 is the MVP service's port and equals the template's own value, so an
    agv01 deployment renders exactly what it always did. A vehicle served by the
    v2 parallel instance needs that instance's port (58105 on factory01) --
    until 2026-10-08 this parameter was declared and never used, so every
    deployment pointed the client at 58005 whatever was passed.

.PARAMETER Force
    Stop the onboard client and deploy over it. Refuses by default: a running
    client means the vehicle may be mid-journey. The stop happens after the
    -WhatIf gate and before the payload is copied, so a dry run never touches
    the vehicle and a client that will not die costs a second, not 80 MB.

.PARAMETER SharedSafetyCredential
    control-server#600. The onboard's production template gives the
    vehicle-safety projection a variable of its own,
    CONTROL_SERVER_ONBOARD_SAFETY_CREDENTIAL, and this script fills it with this
    vehicle's credential from the DPAPI store (OnboardSafetyCredential:<vehicleKey>,
    generated by Set-ControlServerSecret.ps1 -NewVehicleSafetyCredential). A
    vehicle without one is refused. Pass this switch only when the server it
    points at is a single-car one, which answers the shared onboard credential
    alone: the shared credential then goes into that variable, even when this
    vehicle has its own in the store (it is ignored, and said so). A multi-car
    server refuses the shared credential (401), so a wrong guess fails closed.
    An onboard whose template still shares the session variable (the MVP line,
    agv01) is unaffected either way.

.PARAMETER KeepCurrentIo
    workspace#28. Keep the IO target the vehicle's installed configuration
    points at (ioModule.host and ioModule.port, nothing else -- the other
    ioModule keys are this package's wiring and follow the template). Without
    an installed configuration (a first deployment), with one that cannot be
    read, or with only a .previous, the deployment is refused rather than
    falling back to the site file.
    Excludes -UseSiteIo.

.PARAMETER UseSiteIo
    workspace#28. Render the site file's IO module even though the vehicle's
    installed configuration does not already point at it: the slot simulator
    (loopback), an IO host that is neither (unknown), a configuration that
    cannot be read, or an install root with only a .previous. THIS CONNECTS
    THE VEHICLE TO REAL IO: switching to the real module is in the "moves a
    vehicle" class, so get the user's authorisation for this occasion and have
    someone on site before passing it. Without it, each of those deployments
    is refused. A vehicle already on the site file's module (agv01) and a
    first deployment take the site value without either switch, as they always
    did. Excludes -KeepCurrentIo.

.PARAMETER WhatIf
    Stage, verify and render the configuration locally, then stop before the
    vehicle is touched. The rendered configuration is printed. The read-only
    probes (is the client running, where does the installed IO point) still
    run, so the IO decision shows up in a dry run too.

.EXAMPLE
    ./06-deploy-onboard-hmi.ps1 -WhatIf

.EXAMPLE
    ./06-deploy-onboard-hmi.ps1 -RunId 12345678

.EXAMPLE
    ./06-deploy-onboard-hmi.ps1 -SshAlias agv02 -KeepCurrentIo -WhatIf
    A test vehicle on the slot simulator: deploy and keep it on the simulator.
#>
[CmdletBinding(SupportsShouldProcess = $true, DefaultParameterSetName = 'Download')]
param(
    [Parameter(ParameterSetName = 'Download')]
    [string] $RunId,

    [Parameter(Mandatory = $true, ParameterSetName = 'Local')]
    [string] $PackagePath,

    [string] $SshAlias = 'agv01',

    [string] $Repository = 'trytoreachpeak0/8005-agv-control-server',

    [string] $SitePath,

    [string] $SecretPath = (Join-Path $env:LOCALAPPDATA 'AgvOpsSecrets\control-server-deployment.xml'),

    [string] $ControlServerHost = '172.19.205.222',

    [ValidateRange(1, 65535)]
    [int] $OnboardPort = 58005,

    [ValidateRange(1, 65535)]
    [int] $HealthPort = 58007,

    [string] $StagingRoot = 'C:\temp\agv\onboard-staging',

    [switch] $Force,

    [switch] $SharedSafetyCredential,

    [switch] $KeepCurrentIo,

    [switch] $UseSiteIo
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 3.0

$scriptRoot = $PSScriptRoot
if (-not $SitePath) {
    $SitePath = Join-Path (Split-Path -Parent $scriptRoot) "config\site-$SshAlias.json"
}
# .Replace rather than -replace: the right-hand side of -replace is a regular
# expression, where a lone backslash is an error rather than a backslash.
$toPosix = { param($p) $p.Replace('\', '/') }

function Write-Step {
    param([string] $Message)
    Write-Host ("[{0:HH:mm:ss}] {1}" -f (Get-Date), $Message) -ForegroundColor Cyan
}

function Invoke-Ssh {
    param([string[]] $Arguments, [switch] $Quiet)
    $output = & ssh $SshAlias @Arguments 2>&1
    if (-not $Quiet) { $output | ForEach-Object { Write-Host "  $_" } }
    if ($LASTEXITCODE -ne 0) { throw "ssh $SshAlias failed (exit $LASTEXITCODE)" }
    return $output
}

function Resolve-VehicleSafetyCredential {
    <#
        control-server#600. Which stored credential this vehicle's projection poll presents, and the variable it goes in.
        Pure: Test-DeployOnboardHmi.ps1 lifts it out by its AST. Returns StoreKey and Variable; never reads a value.
    #>
    param(
        [Parameter(Mandatory = $true)][string] $SafetyVariable,
        [Parameter(Mandatory = $true)][string] $SessionVariable,
        [Parameter(Mandatory = $true)][string] $VehicleKey,
        [AllowEmptyCollection()][string[]] $StoreKeys = @(),
        [switch] $SharedSafetyCredential
    )
    # A template that reads the projection with the session's own variable (the MVP onboard) keeps the shared credential.
    if ($SafetyVariable -ceq $SessionVariable) {
        return [pscustomobject]@{ StoreKey = 'OnboardCredential'; Variable = $SafetyVariable; Reason = 'the template shares the session credential' }
    }
    $own = 'OnboardSafetyCredential:' + $VehicleKey
    # Review S2: the explicit switch wins. Credentials generated for a multi-car instance stay in the store; a vehicle
    # deployed against a single-car instance must still get the shared one, which is all that instance answers.
    if ($SharedSafetyCredential) {
        $ignored = ($StoreKeys -ccontains $own) ? "; $own is in the store and was ignored" : ''
        return [pscustomobject]@{ StoreKey = 'OnboardCredential'; Variable = $SafetyVariable; Reason = "-SharedSafetyCredential: a single-car server$ignored" }
    }
    if ($StoreKeys -ccontains $own) {
        return [pscustomobject]@{ StoreKey = $own; Variable = $SafetyVariable; Reason = 'this vehicle''s own projection credential' }
    }
    throw ("VEHICLE_SAFETY_CREDENTIAL_MISSING: the store has no projection credential for $VehicleKey ($own). Generate one with " +
        '../../factory-server/scripts/control-server/Set-ControlServerSecret.ps1 -NewVehicleSafetyCredential <alias> and deploy ' +
        'the server again, or pass -SharedSafetyCredential if the server this vehicle uses is a single-car one.')
}

function Assert-VehicleSafetyEndpointNamesVehicle {
    <#
        control-server#600. The projection endpoint may name the vehicle (?vehicleKey=); when it does, it must be this one.
        An endpoint naming no vehicle (the MVP template) passes. Pure: Test-DeployOnboardHmi.ps1 lifts it out.
    #>
    param([Parameter(Mandatory = $true)][string] $Endpoint, [Parameter(Mandatory = $true)][string] $VehicleKey)
    $named = [System.Web.HttpUtility]::ParseQueryString(([uri] $Endpoint).Query)['vehicleKey']
    if ($null -ne $named -and $named -cne $VehicleKey) {
        throw "vehicleSafety.endpoint names vehicle '$named', but expectedVehicleKey is '$VehicleKey'."
    }
}

function Test-SimulatorIoHost {
    <#
        workspace#28. The slot simulator runs on the vehicle itself, so a loopback IO host is the simulator. Only these
        spellings count: 127.x, ::1 and localhost. Pure: Test-DeployOnboardHmi.ps1 lifts it out.
    #>
    param([AllowNull()][AllowEmptyString()][string] $IoHost)
    if ([string]::IsNullOrWhiteSpace($IoHost)) { return $false }
    $trimmed = $IoHost.Trim()
    if ($trimmed -ieq 'localhost') { return $true }
    $address = [ipaddress]::Any
    return [ipaddress]::TryParse($trimmed, [ref]$address) -and [ipaddress]::IsLoopback($address)
}

function Get-IoTargetKind {
    <#
        workspace#28 review S3. 'simulator' (loopback), 'real' (exactly the site file's module) or 'unknown'
        (anything else: localhost., a host with a port in it, the machine's own name, another module). Unknown is
        never taken for the real module, so a spelling nobody listed fails towards a refusal rather than a pass.
        Pure: Test-DeployOnboardHmi.ps1 lifts it out.
    #>
    param([AllowNull()][AllowEmptyString()][string] $IoHost, [Parameter(Mandatory = $true)][string] $SiteHost)
    if (Test-SimulatorIoHost $IoHost) { return 'simulator' }
    if (-not [string]::IsNullOrWhiteSpace($IoHost) -and $IoHost.Trim() -ieq $SiteHost.Trim()) { return 'real' }
    return 'unknown'
}

function Resolve-OnboardIoTarget {
    <#
        workspace#28. Which IO target the rendered configuration gets: ioModule.host and ioModule.port only.
        $Installed describes the vehicle's installed appsettings.json: State is 'absent' (first deployment), 'present'
        (with Host and Port), 'unreadable' (with Error) or 'previous-only' (no install root, but <root>.previous has a
        configuration -- a placement that died between its two moves; with PreviousHost and PreviousPort, or Error).
        Returns Host, Port, Line (the summary line) and Warning. Pure: Test-DeployOnboardHmi.ps1 lifts it out.

        The rule it holds: no combination of switches moves a vehicle that is not already on the site file's real
        module onto it unless -UseSiteIo says so, because switching to real IO needs the user's authorisation for that
        occasion. The one exception is a genuine first deployment, which has always taken the site value.
    #>
    param(
        [Parameter(Mandatory = $true)][hashtable] $Installed,
        [Parameter(Mandatory = $true)][string] $SiteHost,
        [Parameter(Mandatory = $true)][int] $TemplatePort,
        [switch] $KeepCurrentIo,
        [switch] $UseSiteIo
    )
    if ($KeepCurrentIo -and $UseSiteIo) {
        throw 'IO_OPTIONS_EXCLUSIVE: -KeepCurrentIo and -UseSiteIo contradict each other; pass one.'
    }
    $labels = @{ simulator = 'simulator'; real = 'REAL MODULE'; unknown = 'UNKNOWN IO' }
    $describe = { param($h, $p) '{0} {1}:{2}' -f $labels[(Get-IoTargetKind $h $SiteHost)], $h, $p }
    $errorText = $Installed['Error'] ? ": $($Installed['Error'])" : ''

    $state = [string] $Installed['State']
    $installedHost = [string] $Installed['Host']
    $installedPort = 0
    $installedValid = $state -ceq 'present' -and -not [string]::IsNullOrWhiteSpace($installedHost) -and
        $installedHost -notlike '*REPLACE*' -and [int]::TryParse([string] $Installed['Port'], [ref]$installedPort) -and
        $installedPort -ge 1 -and $installedPort -le 65535
    $installedKind = $installedValid ? (Get-IoTargetKind $installedHost $SiteHost) : $null
    $previous = switch ($true) {
        ($state -ceq 'absent') { 'none (no installed configuration: first deployment)'; break }
        ($state -ceq 'previous-only') {
            "none in the install root, but its .previous holds one ($(& $describe ([string] $Installed['PreviousHost']) $Installed['PreviousPort'])$errorText)"; break
        }
        $installedValid { & $describe $installedHost $installedPort; break }
        default { "unknown ($state$errorText; host '$installedHost', port '$($Installed['Port'])')" }
    }
    $previousOnly = 'IO_PREVIOUS_INSTALL_ONLY: the install root has no configuration but its .previous does -- a ' +
        "placement that stopped between its two moves leaves exactly this. Before: $previous. Check on the vehicle what " +
        'happened and restore or remove the .previous directory before deploying; this script will not guess which IO ' +
        'the vehicle was meant to use.'

    if ($KeepCurrentIo) {
        if ($state -ceq 'absent') {
            throw ('IO_KEEP_NO_INSTALLED_CONFIG: -KeepCurrentIo keeps the IO target of the installed configuration, and this ' +
                'vehicle has none (first deployment). Refusing rather than silently using the site file''s IO module. ' +
                'Deploy without -KeepCurrentIo to take the site value, then 09-switch-io-module.ps1 -Simulator if the simulator is wanted.')
        }
        if ($state -ceq 'previous-only') { throw $previousOnly }
        if (-not $installedValid) {
            throw "IO_KEEP_UNREADABLE: -KeepCurrentIo could not read a usable ioModule.host/port from the installed configuration: $previous. Refusing rather than guessing."
        }
        return [pscustomobject]@{
            Host    = $installedHost
            Port    = $installedPort
            Line    = "IO target: $(& $describe $installedHost $installedPort), kept from the installed configuration (-KeepCurrentIo); before: $previous"
            Warning = $null
        }
    }

    $toReal = (Get-IoTargetKind $SiteHost $SiteHost) -ceq 'real'
    # Anything but the site's own module already, or a genuine first deployment, is a switch onto real IO.
    $switching = $toReal -and $state -cne 'absent' -and $installedKind -cne 'real'
    $target = & $describe $SiteHost $TemplatePort
    $choose = 'Pass one of: -KeepCurrentIo to keep the current IO target, or -UseSiteIo to switch to the real module ' +
        '(authorised, with someone on site).'
    if ($switching -and -not $UseSiteIo) {
        if ($state -ceq 'previous-only') { throw $previousOnly }
        if ($installedKind -ceq 'unknown') {
            throw ("IO_UNKNOWN_TO_REAL_REFUSED: the installed configuration's IO is $previous -- neither the simulator (loopback) " +
                "nor the site file's module -- and the site file would switch it to $target. Switching a vehicle to real IO " +
                "needs the user's authorisation. $choose")
        }
        # Simulator, or an installed configuration this script cannot read, which may well point at the simulator.
        throw ("IO_SIMULATOR_TO_REAL_REFUSED: the installed configuration's IO is $previous, and the site file would switch it to " +
            "$target. Switching a vehicle to real IO needs the user's authorisation. $choose")
    }
    $line = "IO target: $target, from the site file; before: $previous"
    if ($UseSiteIo -and $toReal) {
        $line += ' -- -UseSiteIo: this connects the vehicle to REAL IO; deploy only with the user''s authorisation and someone on site'
    }
    $warning = $switching ?
        "This deployment switches the vehicle's IO from $previous to $target (-UseSiteIo). The vehicle will drive real slot IO the next time the client starts." :
        $null
    return [pscustomobject]@{ Host = $SiteHost; Port = $TemplatePort; Line = $line; Warning = $warning }
}

Write-Step "OnboardHmi deployment to $SshAlias"

# Before anything is downloaded or read: the two IO switches contradict each other.
if ($KeepCurrentIo -and $UseSiteIo) {
    throw 'IO_OPTIONS_EXCLUSIVE: -KeepCurrentIo and -UseSiteIo contradict each other; pass one.'
}

# ---------------------------------------------------------------- site values ---

if (-not (Test-Path -LiteralPath $SitePath)) {
    throw @"
No site file at $SitePath.
Copy config\site.example.json to that name and fill in the vehicle's
values. Refusing to guess: onboardInstanceId must stay stable across
deployments, and the rule-gateway and IO-module addresses are wiring facts.
"@
}
$site = Get-Content -Raw -LiteralPath $SitePath | ConvertFrom-Json
Write-Step "Site values from $(Split-Path -Leaf $SitePath)"

$installRoot = $site.install.root
$siteReplacements = [ordered]@{
    REPLACE_CONTROL_SERVER_IP        = $ControlServerHost
    REPLACE_CONTROL_SERVER_HOST      = "${ControlServerHost}:$HealthPort"
    REPLACE_WITH_STABLE_UUID         = $site.wireToGate.onboardInstanceId
    REPLACE_WITH_EXPECTED_VEHICLE_KEY = $site.vehicleSafety.expectedVehicleKey
    REPLACE_RULE_SERVER_IP           = $site.ruleGateway.host
    REPLACE_IO_MODULE_IP             = $site.ioModule.host
}
foreach ($entry in $siteReplacements.GetEnumerator()) {
    if ([string]::IsNullOrWhiteSpace($entry.Value) -or $entry.Value -like 'REPLACE_*') {
        throw "Site value for $($entry.Key) is still a placeholder in $SitePath."
    }
}

# ------------------------------------------------------------------- secrets ---

if (-not (Test-Path -LiteralPath $SecretPath)) {
    throw "No secret store at $SecretPath. Run ../factory-server/scripts/control-server/Set-ControlServerSecret.ps1 -Import first."
}
$secrets = Import-Clixml -LiteralPath $SecretPath
$plain = @{}
foreach ($key in @('OnboardCredential', 'OperatorId')) {
    if (-not $secrets.ContainsKey($key) -or -not $secrets[$key]) {
        throw "Secret '$key' is missing from $SecretPath."
    }
    $plain[$key] = [System.Net.NetworkCredential]::new('', $secrets[$key]).Password
}
Write-Step 'Secrets loaded from the DPAPI store'

# -------------------------------------------------------------- vehicle state ---

# A running client means the vehicle may be mid-journey. Replacing its binaries
# underneath it is the one failure mode this whole script exists to avoid.
$running = Invoke-Ssh -Quiet @("if (Get-Process SQCD.Agv.Wpf -ErrorAction SilentlyContinue) { 'RUNNING' } else { 'STOPPED' }")
$stopBeforePlacing = $false
if ($running -contains 'RUNNING') {
    if (-not $Force) {
        throw "SQCD.Agv.Wpf is running on $SshAlias. Stop it from the vehicle's own desktop session, then rerun. Use -Force only if you know the vehicle is idle."
    }
    # -Force used to skip this throw and nothing else, which was worse than
    # refusing outright: the running client keeps handles on its own binaries,
    # so the deployment ran all the way to `Move-Item $root $previous` and died
    # there with "the process cannot access the file", leaving the payload in
    # $root.incoming and no .previous. Stopping the client is what -Force has to
    # mean if it is to mean anything.
    $stopBeforePlacing = $true
    Write-Warning "SQCD.Agv.Wpf is running on $SshAlias and -Force was given; it will be stopped before the payload is placed."
}
Write-Step "Onboard client state on ${SshAlias}: $($running -join ' ')"

# workspace#28. Where the installed configuration's IO points, read before the -WhatIf gate (read-only, like the
# check above) so a dry run shows the IO decision too. Encoded, so no quoting survives two shells by accident.
$ioProbe = @"
`$root = '$installRoot'
function Read-IoTarget([string] `$file) {
    `$io = (Get-Content -Raw -LiteralPath `$file | ConvertFrom-Json -AsHashtable)['ioModule']
    if (`$io -isnot [System.Collections.IDictionary]) { return @{ Host = `$null; Port = `$null } }
    return @{ Host = `$io['host']; Port = `$io['port'] }
}
`$path = Join-Path `$root 'appsettings.json'
if (-not (Test-Path -LiteralPath `$path -PathType Leaf)) {
    # Review S2: a placement that died between its two moves leaves no root but a .previous; that is not a first deployment.
    `$previous = Join-Path "`$root.previous" 'appsettings.json'
    if (Test-Path -LiteralPath `$previous -PathType Leaf) {
        try { `$t = Read-IoTarget `$previous; `$state = @{ State = 'previous-only'; PreviousHost = `$t.Host; PreviousPort = `$t.Port } }
        catch { `$state = @{ State = 'previous-only'; Error = `$_.Exception.Message } }
    } else {
        `$state = @{ State = 'absent' }
    }
    'IO-STATE ' + (`$state | ConvertTo-Json -Compress)
    return
}
try {
    `$t = Read-IoTarget `$path
    'IO-STATE ' + (@{ State = 'present'; Host = `$t.Host; Port = `$t.Port } | ConvertTo-Json -Compress)
} catch {
    'IO-STATE ' + (@{ State = 'unreadable'; Error = `$_.Exception.Message } | ConvertTo-Json -Compress)
}
"@
$ioProbeEncoded = [Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($ioProbe))
$ioProbeLine = @(Invoke-Ssh -Quiet @("pwsh -NoProfile -EncodedCommand $ioProbeEncoded") | ForEach-Object { "$_" } |
        Where-Object { $_.StartsWith('IO-STATE ') }) | Select-Object -Last 1
$installedIo = $null
if ($ioProbeLine) {
    try { $installedIo = $ioProbeLine.Substring('IO-STATE '.Length) | ConvertFrom-Json -AsHashtable } catch { $installedIo = $null }
}
if ($installedIo -isnot [hashtable] -or -not $installedIo.ContainsKey('State')) {
    $installedIo = @{ State = 'unreadable'; Error = 'the probe returned no IO-STATE line' }
}
Write-Step "Installed IO on ${SshAlias}: $($installedIo['State']) $($installedIo['Host']):$($installedIo['Port'])"

# ------------------------------------------------------------------- package ---

# -WhatIf:$false on every local staging operation below. SupportsShouldProcess
# puts the whole script into WhatIf mode, which would otherwise skip creating
# this directory and then fail reading from it. WhatIf here means "do not touch
# the vehicle", not "do not use a scratch directory" -- and staging for real is
# what lets the dry run verify the hash and render the configuration, which is
# the whole point of running it.
$localStage = Join-Path $env:TEMP "onboard-deploy-$(Get-Date -Format 'yyyyMMdd-HHmmss')"
New-Item -ItemType Directory -Path $localStage -Force -WhatIf:$false | Out-Null

try {
    if ($PSCmdlet.ParameterSetName -eq 'Local') {
        $zip = (Resolve-Path -LiteralPath $PackagePath).Path
        Write-Step "Using local package $zip"
    } else {
        if (-not $RunId) {
            Write-Step "Finding the most recent successful release run in $Repository"
            $RunId = & gh run list --repo $Repository --workflow release.yml `
                --status success --limit 1 --json databaseId --jq '.[0].databaseId'
            if ($LASTEXITCODE -ne 0 -or -not $RunId) {
                throw "No successful release run found in $Repository."
            }
        }
        Write-Step "Downloading artifact from run $RunId"
        & gh run download $RunId --repo $Repository --dir $localStage
        if ($LASTEXITCODE -ne 0) { throw "gh run download failed (exit $LASTEXITCODE)" }

        $zip = @(Get-ChildItem -LiteralPath $localStage -Filter '*.zip' -Recurse -File) |
            Sort-Object LastWriteTime -Descending |
            Select-Object -First 1 -ExpandProperty FullName
        if (-not $zip) { throw "Run $RunId produced no zip artifact." }
    }

    $hashFile = "$zip.sha256"
    if (-not (Test-Path -LiteralPath $hashFile)) {
        throw "Missing hash file $hashFile. Refusing to deploy an unverified package."
    }
    $expected = ((Get-Content -LiteralPath $hashFile -Raw) -split '\s+')[0].ToLowerInvariant()
    $actual = (Get-FileHash -LiteralPath $zip -Algorithm SHA256).Hash.ToLowerInvariant()
    if ($expected -ne $actual) {
        throw "Package hash mismatch on the control host. Expected $expected, got $actual."
    }
    Write-Step "Package hash verified ($actual)"

    $unpacked = Join-Path $localStage 'unpacked'
    Expand-Archive -LiteralPath $zip -DestinationPath $unpacked -Force -WhatIf:$false
    $onboardDirectory = Join-Path $unpacked 'onboard-hmi'
    if (-not (Test-Path -LiteralPath $onboardDirectory -PathType Container)) {
        throw "The package has no onboard-hmi directory: $onboardDirectory"
    }

    $manifest = Get-Content -Raw -LiteralPath (Join-Path $unpacked 'release-manifest.json') | ConvertFrom-Json
    $onboardCommit = $manifest.components.onboardHmi.commit
    Write-Step "OnboardHmi commit:    $onboardCommit"
    Write-Step "ControlServer commit: $($manifest.components.controlServer.commit)"

    # ------------------------------------------------------- configuration ---

    # The client reads only appsettings.json from its own directory -- there is
    # no appsettings.<environment>.json layering. So the production template is
    # rendered here and shipped as appsettings.json outright, replacing the
    # development default that ships in the package with wireToGate.enabled
    # false and an unresolvable endpoint.
    $templatePath = Join-Path $onboardDirectory 'appsettings.Production.template.json'
    if (-not (Test-Path -LiteralPath $templatePath -PathType Leaf)) {
        throw "The package carries no appsettings.Production.template.json."
    }
    $rendered = Get-Content -Raw -LiteralPath $templatePath
    foreach ($entry in $siteReplacements.GetEnumerator()) {
        $rendered = $rendered.Replace($entry.Key, $entry.Value)
    }

    $leftover = @([regex]::Matches($rendered, 'REPLACE_[A-Z0-9_]+') | ForEach-Object { $_.Value } | Sort-Object -Unique)
    if ($leftover.Count -gt 0) {
        throw "The rendered configuration still contains placeholders: $($leftover -join ', ')"
    }

    # Read the result back rather than trusting the substitution. Every check
    # below is a startup failure the client would otherwise hit on the vehicle,
    # with a person standing next to it. They mirror
    # SQCD.Agv.Infrastructure/Configuration.cs -- when that file's rules change,
    # these have to follow, or this script starts passing configurations the
    # client rejects.
    $config = $rendered | ConvertFrom-Json

    # The two top-level identities come from the site file, not from the
    # template -- which ships them as AGV-8005-01 / OBU-8005-01. Apply them
    # before validating, or every check below reads the template's sample values
    # and no site file can ever pass.
    $config.agvId = $site.agvId
    $config.onboardInstanceId = $site.onboardInstanceId

    # The template carries no placeholder for the port, only the MVP's 58005,
    # so the string replacement above cannot reach it. Set it as a number and
    # read it back: a string "58105" would fail the client's integer binding.
    if (-not ($config.wireToGate.PSObject.Properties.Name -contains 'port')) {
        throw 'The template has no wireToGate.port; refusing to add a key the client may not read.'
    }
    $config.wireToGate.port = $OnboardPort
    if ($config.wireToGate.port -isnot [int] -or $config.wireToGate.port -ne $OnboardPort) {
        throw "wireToGate.port reads back as '$($config.wireToGate.port)', not $OnboardPort."
    }
    Write-Step "wireToGate endpoint: $($config.wireToGate.host):$($config.wireToGate.port)"

    # workspace#28. The IO target: the site file's module on the template's port, or the installed one with
    # -KeepCurrentIo. Refuses a silent simulator-to-real switch. Only host and port; the rest is this package's wiring.
    if (-not ($config.ioModule.PSObject.Properties.Name -contains 'port')) {
        throw 'The template has no ioModule.port; refusing to add a key the client may not read.'
    }
    $ioTarget = Resolve-OnboardIoTarget -Installed $installedIo -SiteHost ([string] $site.ioModule.host) `
        -TemplatePort ([int] $config.ioModule.port) -KeepCurrentIo:$KeepCurrentIo -UseSiteIo:$UseSiteIo
    $config.ioModule.host = $ioTarget.Host
    $config.ioModule.port = $ioTarget.Port
    Write-Step $ioTarget.Line
    if ($ioTarget.Warning) { Write-Warning $ioTarget.Warning }

    # OnboardSettings.IsPlaceholderValue, reproduced exactly. Note that the two
    # sample identities are themselves placeholders: a site file copied from the
    # example and left with agvId AGV-8005-01 renders a configuration that looks
    # complete, carries no REPLACE_ token, and still throws at startup with
    # "Production环境必须配置真实且稳定的AgvId和OnboardInstanceId".
    $placeholderExact = @('AGV-8005-01', 'OBU-8005-01')
    $placeholderSubstrings = @('REPLACE', 'EXAMPLE', 'CHANGEME', 'YOUR_', 'YOUR-', 'TODO')
    function Test-Placeholder([string]$Value) {
        if ([string]::IsNullOrWhiteSpace($Value)) { return $true }
        $trimmed = $Value.Trim()
        if ($placeholderExact -contains $trimmed) { return $true }
        foreach ($token in $placeholderSubstrings) {
            if ($trimmed -like "*$token*") { return $true }
        }
        return $false
    }

    # WireToGateSettings.IsForbiddenProductionHost: a loopback address is a
    # development leftover, and on the vehicle it would point the client at
    # itself rather than at the server.
    # Not $Host as the parameter name: that is an automatic variable in
    # PowerShell, and shadowing it inside a function is a trap rather than a
    # convenience.
    function Test-ForbiddenHost([string]$Candidate) {
        if (Test-Placeholder $Candidate) { return $true }
        if ($Candidate -in @('localhost', '0.0.0.0', '::')) { return $true }
        $address = [ipaddress]::Any
        if ([ipaddress]::TryParse($Candidate, [ref]$address)) {
            return [ipaddress]::IsLoopback($address)
        }
        return $false
    }

    foreach ($pair in @(
        @{ Name = 'agvId';                       Value = $config.agvId }
        @{ Name = 'onboardInstanceId';           Value = $config.onboardInstanceId }
        @{ Name = 'ruleGateway.host';            Value = $config.ruleGateway.host }
        @{ Name = 'ioModule.host';               Value = $config.ioModule.host }
        @{ Name = 'vehicleSafety.expectedVehicleKey'; Value = $config.vehicleSafety.expectedVehicleKey }
    )) {
        if (Test-Placeholder $pair.Value) {
            throw "$($pair.Name) is '$($pair.Value)', which the client treats as a placeholder and rejects in Production."
        }
    }

    if (Test-ForbiddenHost $config.wireToGate.host) {
        throw "wireToGate.host is '$($config.wireToGate.host)', which the client forbids in Production (loopback, wildcard or placeholder)."
    }

    # WireToGateSettings.Validate: the instance id must parse as a Guid in "D"
    # form, and the build commit must be 40 hex digits that are not all zero.
    $parsedGuid = [guid]::Empty
    if (-not [guid]::TryParseExact($config.wireToGate.onboardInstanceId, 'D', [ref]$parsedGuid)) {
        throw "wireToGate.onboardInstanceId '$($config.wireToGate.onboardInstanceId)' is not a Guid in 'D' form (8-4-4-4-12); the client rejects it."
    }

    # Production refuses to fall back to the legacy rule protocol.
    if (-not $config.wireToGate.enabled) {
        throw 'wireToGate.enabled must stay true; Production forbids falling back to the rule protocol alone.'
    }

    #   the client hard-rejects the TLS-era keys by name, not by value, and
    #   throws WIRE_TO_GATE配置键<键名>已移除 at startup if either is present;
    foreach ($banned in @('useTls', 'serverCertificateSha256')) {
        if ($config.wireToGate.PSObject.Properties.Name -contains $banned) {
            throw "The rendered configuration carries the removed TLS-era key wireToGate.$banned. Delete the key; setting it to false is not enough."
        }
    }
    #   VehicleSafetySettings.Validate accepts only the http scheme;
    if ($config.vehicleSafety.endpoint -notmatch '^http://') {
        throw "vehicleSafety.endpoint must be a plaintext http URI, got: $($config.vehicleSafety.endpoint)"
    }
    # Only now is the [uri] cast safe; the same forbidden-host rule applies to
    # the projection endpoint as to the transport host.
    $safetyHost = ([uri]$config.vehicleSafety.endpoint).Host
    if (Test-ForbiddenHost $safetyHost) {
        throw "vehicleSafety.endpoint points at '$safetyHost', which the client forbids in Production (loopback, wildcard or placeholder)."
    }
    #   the safety gate is not optional;
    if (-not $config.vehicleSafety.enabled) {
        throw 'vehicleSafety.enabled must stay true.'
    }
    #   and onboardBuildCommit is reported to the server during the handshake,
    #   so it must be this package's onboard build and not the older commit the
    #   development default carries.
    if ($config.wireToGate.onboardBuildCommit -ne $onboardCommit) {
        throw "wireToGate.onboardBuildCommit is $($config.wireToGate.onboardBuildCommit) but this package built $onboardCommit."
    }

    # control-server#600: the projection is read with this vehicle's own credential, and the endpoint names this vehicle.
    $safetyChoice = Resolve-VehicleSafetyCredential -SafetyVariable ([string] $config.vehicleSafety.credentialEnvironmentVariable) `
        -SessionVariable ([string] $config.wireToGate.credentialEnvironmentVariable) `
        -VehicleKey ([string] $config.vehicleSafety.expectedVehicleKey) -StoreKeys @($secrets.Keys | Where-Object { $secrets[$_] }) `
        -SharedSafetyCredential:$SharedSafetyCredential
    $safetyCredential = [System.Net.NetworkCredential]::new('', $secrets[$safetyChoice.StoreKey]).Password
    Assert-VehicleSafetyEndpointNamesVehicle -Endpoint ([string] $config.vehicleSafety.endpoint) -VehicleKey ([string] $config.vehicleSafety.expectedVehicleKey)
    Write-Step "Vehicle-safety credential: $($safetyChoice.Variable) from $($safetyChoice.StoreKey) ($($safetyChoice.Reason)); value not shown"

    $renderedPath = Join-Path $localStage 'appsettings.json'
    $config | ConvertTo-Json -Depth 12 | Set-Content -LiteralPath $renderedPath -Encoding utf8NoBOM -WhatIf:$false
    Write-Step 'Configuration rendered and validated'

    if (-not $PSCmdlet.ShouldProcess($SshAlias, "Deploy onboard $($onboardCommit.Substring(0,7)) to $installRoot")) {
        Write-Step 'WhatIf: stopping before the vehicle is touched.'
        Write-Host (Get-Content -Raw -LiteralPath $renderedPath)
        return
    }

    # --------------------------------------------------------- vehicle stop ---

    # Deliberately after the ShouldProcess gate: -WhatIf must not stop a client
    # on a real vehicle. And deliberately before the payload copy, so a client
    # that refuses to die costs a second rather than 80 MB.
    #
    # Client only -- the slot simulator is not this script's to touch. Same
    # shape as 10-start-onboard-stack.ps1 -Stop, including its one weakness:
    # CloseMainWindow needs MainWindowHandle, and a session-0 ssh session cannot
    # see a window on the vehicle's session-1 desktop, so over this channel it
    # always degenerates to the kill after the timeout.
    if ($stopBeforePlacing) {
        Write-Step "Stopping SQCD.Agv.Wpf on $SshAlias before it is replaced"
        Invoke-Ssh -Quiet @("Get-Process -Name SQCD.Agv.Wpf -ErrorAction SilentlyContinue | ForEach-Object { `$_.CloseMainWindow() | Out-Null; if (-not `$_.WaitForExit(10000)) { `$_.Kill(); `$_.WaitForExit(10000) | Out-Null } }; if (Get-Process -Name SQCD.Agv.Wpf -ErrorAction SilentlyContinue) { throw 'SQCD.Agv.Wpf is still running on the vehicle.' }") | Out-Null
        Write-Step 'Onboard client stopped'
    }

    # ------------------------------------------------------------ transfer ---

    Write-Step "Staging on $SshAlias"
    Invoke-Ssh @("New-Item -ItemType Directory -Force -Path '$StagingRoot' | Out-Null; 'ready'")

    $payload = Join-Path $localStage 'onboard-payload.zip'
    Copy-Item -LiteralPath $renderedPath -Destination (Join-Path $onboardDirectory 'appsettings.json') -Force
    Remove-Item -LiteralPath (Join-Path $onboardDirectory 'appsettings.Production.template.json') -Force
    Compress-Archive -Path (Join-Path $onboardDirectory '*') -DestinationPath $payload -CompressionLevel Optimal
    $payloadHash = (Get-FileHash -LiteralPath $payload -Algorithm SHA256).Hash.ToLowerInvariant()

    Write-Step "Copying payload ($([math]::Round((Get-Item $payload).Length / 1MB, 1)) MB)"
    $remoteZip = "$StagingRoot\onboard-payload.zip"
    & scp -q $payload "${SshAlias}:$(& $toPosix $remoteZip)"
    if ($LASTEXITCODE -ne 0) { throw "scp of the payload failed (exit $LASTEXITCODE)" }

    # -------------------------------------------------------------- place ---

    # The previous generation is kept beside the install root rather than
    # deleted: the vehicle is the one machine where a bad deployment cannot be
    # fixed by redeploying over a fast link.
    $place = @"
`$ErrorActionPreference = 'Stop'
`$actual = (Get-FileHash -LiteralPath '$remoteZip' -Algorithm SHA256).Hash.ToLowerInvariant()
if (`$actual -ne '$payloadHash') { throw "Payload hash mismatch on the vehicle. Expected $payloadHash, got `$actual." }
'hash verified'

`$root = '$installRoot'
`$previous = "`$root.previous"
`$incoming = "`$root.incoming"
if (Test-Path -LiteralPath `$incoming) { Remove-Item -LiteralPath `$incoming -Recurse -Force }
Expand-Archive -LiteralPath '$remoteZip' -DestinationPath `$incoming -Force
if (Test-Path -LiteralPath `$previous) { Remove-Item -LiteralPath `$previous -Recurse -Force }
if (Test-Path -LiteralPath `$root) { Move-Item -LiteralPath `$root -Destination `$previous }
Move-Item -LiteralPath `$incoming -Destination `$root
"placed: `$root"

# Read the placed configuration back on the vehicle itself: the endpoint the
# client will dial is the one fact a wrong deployment gets wrong silently.
`$placed = Get-Content -Raw -LiteralPath (Join-Path `$root 'appsettings.json') | ConvertFrom-Json
`$endpoint = '{0}:{1}' -f `$placed.wireToGate.host, `$placed.wireToGate.port
if (`$endpoint -ne '${ControlServerHost}:$OnboardPort') { throw "Placed wireToGate endpoint is `$endpoint, expected ${ControlServerHost}:$OnboardPort." }
"wireToGate endpoint read back: `$endpoint"
# workspace#28: the IO target is the other fact that decides what the vehicle does when the client starts.
`$ioPlaced = '{0}:{1}' -f `$placed.ioModule.host, `$placed.ioModule.port
if (`$ioPlaced -ne '$($ioTarget.Host):$($ioTarget.Port)') { throw "Placed ioModule is `$ioPlaced, expected $($ioTarget.Host):$($ioTarget.Port)." }
"ioModule read back: `$ioPlaced"

[Environment]::SetEnvironmentVariable('CONTROL_SERVER_ONBOARD_CREDENTIAL', '$($plain['OnboardCredential'])', 'Machine')
[Environment]::SetEnvironmentVariable('CONTROL_SERVER_OPERATOR_ID', '$($plain['OperatorId'])', 'Machine')
# control-server#600: the projection's own variable, when the template gives it one (the same value otherwise).
[Environment]::SetEnvironmentVariable('$($safetyChoice.Variable)', '$($safetyCredential)', 'Machine')
'credentials set (machine scope)'

# On the public desktop rather than one user's: whoever starts this is the
# operator logged in at the vehicle, not necessarily the account that deployed
# it. Recreated every deployment so the target follows the install root.
`$exe = Join-Path `$root 'SQCD.Agv.Wpf.exe'
if (Test-Path -LiteralPath `$exe) {
    `$lnkPath = 'C:\Users\Public\Desktop\8005 AGV 车载端.lnk'
    `$shell = New-Object -ComObject WScript.Shell
    `$lnk = `$shell.CreateShortcut(`$lnkPath)
    `$lnk.TargetPath = `$exe
    `$lnk.WorkingDirectory = `$root
    `$lnk.Description = '8005 AGV 车载上位机（WIRE_TO_GATE）'
    `$lnk.Save()
    [void][System.Runtime.InteropServices.Marshal]::ReleaseComObject(`$shell)
    "shortcut: `$lnkPath"
} else {
    "shortcut skipped: `$exe not found"
}

# Read the body, do not trust a handshake. This is the check that decides
# whether the client will leave RecoveryRequired, and it can only be made from
# the vehicle.
try {
    `$safety = Invoke-WebRequest -Uri '$($config.vehicleSafety.endpoint)' ``
        -Headers @{ Authorization = 'Bearer $($safetyCredential)' } ``
        -NoProxy -TimeoutSec 15 -UseBasicParsing -SkipHttpErrorCheck
    "vehicle-safety `$(`$safety.StatusCode): `$(`$safety.Content)"
} catch {
    "vehicle-safety UNREACHABLE: `$(`$_.Exception.Message)"
}
"@
    $placePath = Join-Path $localStage 'place-onboard.ps1'
    Set-Content -LiteralPath $placePath -Value $place -Encoding utf8NoBOM
    $remotePlace = "$StagingRoot\place-onboard.ps1"
    & scp -q $placePath "${SshAlias}:$(& $toPosix $remotePlace)"
    if ($LASTEXITCODE -ne 0) { throw "scp of the placement script failed (exit $LASTEXITCODE)" }

    Write-Step 'Placing the payload on the vehicle'
    $placeOutput = Invoke-Ssh @("pwsh -NoProfile -File `"$remotePlace`"; Remove-Item -LiteralPath `"$remotePlace`" -Force")

    # ------------------------------------------------------------- hand off ---

    Write-Host ''
    Write-Step 'Staged. NOT started -- that part is yours.'
    Write-Step $ioTarget.Line
    if ($ioTarget.Warning) { Write-Warning $ioTarget.Warning }
    Write-Host ''
    Write-Host '  On the vehicle, from a desktop session:' -ForegroundColor Yellow
    Write-Host "    $installRoot\SQCD.Agv.Wpf.exe" -ForegroundColor Yellow
    Write-Host ''
    Write-Host '  Before you do:' -ForegroundColor DarkGray
    Write-Host '    - confirm the vehicle is where you think it is and is meant to move;' -ForegroundColor DarkGray
    Write-Host '    - the vehicle-safety line above must be 200 with a matching vehicleKey,' -ForegroundColor DarkGray
    Write-Host '      motionState=STOPPED and fresh observedAt, or a clean session stays in' -ForegroundColor DarkGray
    Write-Host '      RecoveryRequired / DEPARTURE_SAFETY_NOT_READY. That is the gate working,' -ForegroundColor DarkGray
    Write-Host '      not a bug;' -ForegroundColor DarkGray
    Write-Host "    - the previous build is at $installRoot.previous if you need it back." -ForegroundColor DarkGray

    if ($placeOutput -match 'UNREACHABLE') {
        Write-Warning 'The vehicle could not reach the ControlServer projection endpoint.'
        Write-Warning "Deploy the server half first: ../factory-server/scripts/15-deploy-control-server.ps1"
    }
    # control-server#600 review S3: the server answered, and refused this vehicle. Not a reachability problem.
    if ($placeOutput -match 'vehicle-safety 40[13]') {
        Write-Warning 'The server refused this vehicle''s projection request (401: not this vehicle''s credential on that server; 403: the endpoint''s vehicleKey is not the credential''s vehicle or not in its roster).'
        Write-Warning 'See remote-ops/factory-server/docs/wire-to-gate-parallel-cd.md section 7.2: a multi-car server needs -NewVehicleSafetyCredential and a redeploy; a single-car server needs -SharedSafetyCredential.'
    }

} finally {
    if (Test-Path -LiteralPath $localStage) {
        Remove-Item -LiteralPath $localStage -Recurse -Force -ErrorAction SilentlyContinue -WhatIf:$false
    }
    $plain.Clear()
    $safetyCredential = $null
}
